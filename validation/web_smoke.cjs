const child=spawn(python,['-u',path.join(root,'product/service.py'),'--data-dir',path.join(output,'data')],{windowsHide:true});
const errors=[];child.stderr.on('data',data=>process.stderr.write(data));
let browser;
async function waitFor(check,timeout=45000){const end=Date.now()+timeout;while(Date.now()<end){if(await check())return;await new Promise(r=>setTimeout(r,200));}throw Error('Verification timeout');}
(async()=>{
  const line=await new Promise((resolve,reject)=>{const rl=readline.createInterface({input:child.stdout});rl.once('line',resolve);child.once('exit',code=>reject(Error('Service exited '+code)));});
  const connection=JSON.parse(line);
  const call=async(route,body)=>{const r=await fetch(`http://127.0.0.1:${connection.port}/api${route}`,{method:body?'POST':'GET',headers:{Authorization:'Bearer '+connection.token,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});const value=await r.json();if(!r.ok)throw Error(value.error);return value;};
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:940},deviceScaleFactor:1});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:1420/#port=${connection.port}&token=${connection.token}`);
  await page.getByRole('heading',{name:'图集',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'01-empty.png')});
  const files=['D7000.NEF','EOS_5D_Mark_II.CR2'].map(name=>path.join(__dirname,'inputs',name));
  for(const file of files)if(!fs.existsSync(file))throw Error('Required RAW fixture is missing: '+file);
  const job=await call('/import',{paths:files});
  await waitFor(async()=>{const status=await call('/jobs/'+job.id);if(status.status==='error')throw Error(status.error);if(status.status==='done'&&status.result.errors?.length)throw Error(JSON.stringify(status.result.errors));return status.status==='done';});
  await page.reload();
  await page.getByRole('button',{name:/打开图集 /}).first().click();
  await page.locator('.photo-card').first().waitFor();
  await waitFor(()=>page.locator('.photo-card img').count().then(n=>n===files.length));
  await page.screenshot({path:path.join(output,'02-library.png')});
  await page.locator('article[aria-label="照片 D7000.NEF"]').dblclick();
  const editor=page.getByRole('region',{name:'高精度照片编辑器',exact:true});await editor.waitFor();
  await editor.getByRole('button',{name:'RAW 显影',exact:true}).click();
  const edited=editor.locator('.comparison-edited img'),histogram=editor.locator('.ew-histogram canvas');
  await edited.waitFor();await waitFor(()=>editor.locator('.comparison-edited.loading').count().then(n=>n===0));
  const previewBefore=await edited.getAttribute('src');
  await waitFor(()=>histogram.evaluate(c=>Array.from(c.getContext('2d').getImageData(0,0,c.width,c.height).data).some((v,i)=>i%4===3&&v>0)));
  const histogramBefore=await histogram.evaluate(c=>c.toDataURL());
  await page.getByRole('slider',{name:'RAW 曝光',exact:true}).focus();
  await page.getByRole('slider',{name:'RAW 曝光',exact:true}).press('ArrowRight');
  await waitFor(async()=>{const library=await call('/library');return library.photos.find(p=>p.name==='D7000.NEF').recipe.raw_exposure>0;});
  await waitFor(async()=>await edited.getAttribute('src')!==previewBefore&&await editor.locator('.comparison-edited.loading').count()===0);
  await waitFor(async()=>await histogram.evaluate(c=>c.toDataURL())!==histogramBefore,3000);
  await page.screenshot({path:path.join(output,'03-raw-editor.png')});
  await editor.getByRole('button',{name:'光线与色调',exact:true}).click();
  await page.getByRole('button',{name:'暖日胶片',exact:true}).click();
  await editor.getByRole('button',{name:'照片库',exact:true}).click();
  await waitFor(async()=>{const library=await call('/library');return library.photos.find(p=>p.name==='D7000.NEF').recipe.style==='warm';});
  const thumb=page.locator('article[aria-label="照片 D7000.NEF"] img');
  await thumb.waitFor();await waitFor(()=>page.locator('article[aria-label="照片 D7000.NEF"] .picture.loading').count().then(n=>n===0));
  const oldThumb=await thumb.getAttribute('src');
  await page.getByLabel('撤销上次修改',{exact:true}).click();
  await waitFor(async()=>{const library=await call('/library');return library.photos.find(p=>p.name==='D7000.NEF').recipe.style==='natural';});
  await waitFor(async()=>await thumb.getAttribute('src')!==oldThumb);
  await page.locator('article[aria-label="照片 D7000.NEF"]').dblclick();
  await page.getByRole('button',{name:'暖日胶片',exact:true}).click();
  await editor.getByRole('button',{name:'照片库',exact:true}).click();
  await waitFor(async()=>{const library=await call('/library');return library.photos.find(p=>p.name==='D7000.NEF').recipe.style==='warm';});
  await page.getByRole('button',{name:'精选 D7000.NEF',exact:true}).click();
  await waitFor(async()=>{const library=await call('/library');return library.photos.find(p=>p.name==='D7000.NEF').decision==='keep';});
  await page.getByRole('button',{name:'导出作品',exact:true}).click();
  await page.getByRole('dialog',{name:'导出作品'}).waitFor();
  await page.screenshot({path:path.join(output,'04-export.png')});
  await page.getByLabel('关闭导出').click();
  const library=await call('/library');const photo=library.photos.find(p=>p.name==='D7000.NEF');
  const exported=await call('/export',{ids:[photo.id],folder:path.join(output,'exports'),template:'frame',size:1200});
  await waitFor(async()=>{const job=await call('/jobs/'+exported.id);if(job.status==='error')throw Error(job.error);return job.status==='done';});
  const report={status:'passed',photos:library.photos.length,raw_exposure:photo.recipe.raw_exposure,style:photo.recipe.style,selected:photo.decision,undo_refresh_verified:true,exported:fs.readdirSync(path.join(output,'exports')),browser_errors:errors};
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify({output,...report},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();child.kill();});
